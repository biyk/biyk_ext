# arent/spec3.py — контракт SCHEMA=3: ход = позиция атаки × цель/оружие × позиция после атаки.
#
# v2 (spec.SCHEMA=2) кодирует ход одной клеткой = финальной: sim сворачивает все MOVE и бьёт
# из итоговой клетки, поэтому «выстрелить с места и отступить» невыразимо. v3 меняет ТОЛЬКО
# представление действия (голову клеток -> голову move-plan'ов (attack_cell, end_cell) в бюджете
# движения) и способ его исполнения (sim.apply_actor_seq: удар из текущей клетки). Вектор
# состояния (наблюдение) остаётся как в v2, чтобы не площить признаки; bump схемы обязателен,
# потому что меняется состав/размер головы клеток -> dims() отличается -> старые v2-веса net.load
# и rl_setup._guard_compat ОТКАЗЫВАЮТ с явной ошибкой (не молча). v2-код/модели/датасеты не
# трогаются: v3 живёт в отдельной схеме и отдельных артефактах.
from typing import Dict

from arent import spec

SCHEMA = 3

# ЯВНАЯ ВЕРСИЯ ПРИЗНАКОВ головы move-plan (ЭТАП 6, часть 1.2).
# SCHEMA=3 задаёт СЕМАНТИКУ действия (move-plan: attack_cell,end_cell), а не состав
# признаков клетки, поэтому смена признаков (убран slotIndex: 22 -> 21 на ЭТАПЕ 5) НЕ
# должна трогать номер схемы. Отделяем её отдельным номером:
#   v1 = голова с позиционным slotIndex (ширина 22) — до ЭТАПА 5;
#   v2 = permutation-invariant голова без slotIndex (ширина 21) — ЭТАП 5/6;
#   v3 = +coverLos/atChokeEnd в голове move-plan (ширина 23) — ЭТАП 4 (укрытия и узости).
# Пишется в dims3() и в каждый пример, сверяется при загрузке чекпойнта и датасета: модель
# или выборка версии v1/v2 (cell_feat=22/21) ОТВЕРГАЮТСЯ новым конвейером явно, а не молча.
FEATURES_VERSION = 3
CELL_FEAT_V1 = 22                # ширина старой головы (для сообщения об ошибке/диагностики)

# Голова move-plan: пары (attack_cell, end_cell), достижимые в пределах бюджета хода.
# Последний слот — «не перемещаться» (атака/пропуск с исходной позиции).
K_MOVEPLAN = 48
K_TARGETS = spec.K_TARGETS          # цель/оружие/союзники/патч — как в v2
K_ALLIES = spec.K_ALLIES
K_WEAPONS = spec.K_WEAPONS
PATCH_R = spec.PATCH_R
PATCH_SIZE = spec.PATCH_SIZE
NONE_SLOT = spec.NONE_SLOT

# Признаки одного слота move-plan (порядок задаёт encode_v3.cell_vectors): позиция атаки и
# позиция после атаки (смещения от исходной клетки и дистанции), разбор бюджета, зоны удара
# из позиции атаки, и риск/укрытие в финальной позиции. cover/threat/los заполняет F-C.
#
# ЭТАП 5 (часть 2): убран позиционный признак slotIndex из головы move-plan. Пока индекс слота
# виден сети на входу, разметка учителя, принудительно вставляемая в последний слот (47) при
# усечении меню, превращается в разучиваемую константу: сеть учится «отвечать 47», а не
# содержимому плана. plan-голова — Siamese по слоту, поэтому без slotIndex она становится
# инвариантной к перестановке меню и обязана выбирать по содержимому (adx/ady/canAttack/cover/…).
# Это МЕНЯЕТ состав признаков клетки (22 -> 21): dims3()['cell_feat'] отличается, поэтому
# старые v3-чекпойнты и датасеты ОТКАЗЫВАЮТСЯ грузиться (net.dims_for сверяется в rl_setup и в
# shape весов pure/torch), а не предсказывают молча. v2 (spec.CELL_FEATURES) не тронут.
CELL3_FEATURES: tuple = (
    "slotActive",
    "adx", "ady", "adist",           # позиция атаки относительно исходной
    "edx", "edy", "edist",           # позиция после атаки относительно исходной
    "costIn", "costOut", "costTotal", "budgetFrac",
    "sureAttack", "doubtAttack", "canAttack",     # зона удара ИЗ attack_cell
    "stay", "pureMove", "retreatToOrigin", "gapIncrease",
    "coverFinal", "threatFinal", "losAttack",
    "coverLos", "atChokeEnd",        # ЭТАП 4: LOS-укрытие и узость финальной клетки
)


def dims3() -> Dict[str, int]:
    """Размерности v3: state как в v2, но голова клеток — move-plan'ы с CELL3_FEATURES.

    Включаем feat_version: он попадает в dims чекпойнта, поэтому и PPO-guard
    (_guard_compat сверяет dims целиком), и net.load (сверка ниже) отличают новую голову (21)
    от старой (22) даже при совпадении номера схемы."""
    d = dict(spec.dims())
    d["schema"] = SCHEMA
    d["cells"] = K_MOVEPLAN + 1
    d["cell_feat"] = len(CELL3_FEATURES)
    d["feat_version"] = FEATURES_VERSION
    return d
